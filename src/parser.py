"""Модуль для разбора пользовательского ввода на команды и аргументы""" # Это docstring (правило К1: документация вместо комментариев #)

def parse_input(user_input: str) -> tuple[str, list[str]]: # Объявляем функцию. Указываем типы: на вход строка, на выход кортеж (строка, список строк).
    """эта функция парсит команду пользователя и разделяет её по пробелам""" # Описание функции (правило К1)

    parts = user_input.strip().split()
    if not parts:
        return "", []

    return parts[0], parts[1:]